//! Solum crypto layer: **Crypt4GH** envelopes for clinical field categories.
//!
//! Crypt4GH is a universal envelope encryption scheme (X25519 header +
//! ChaCha20-Poly1305 segments). Ferrum uses it for genomic DRS objects; Solum
//! uses the **same format** for clinical category blobs so keys, tooling, and
//! threat models stay aligned across the Synaptic Four portfolio.
//!
//! There is no HL7 “encrypt any FHIR element at rest” standard that replaces
//! this. JWE appears in SMART Health Links / bulk-export *sharing* flows, not
//! as a general at-rest field envelope for compliance layers — see
//! `docs/CRYPTO.md`.
//!
//! ## Customer-held keys
//!
//! Under [`KeyCustody::CustomerHeld`], Solum **never** generates Crypt4GH
//! keypairs. Callers register customer-supplied public (and, for decrypt,
//! private) keys via a [`Crypt4ghKeyProvider`]. Ephemeral in-memory keygen is
//! confined to [`EphemeralTestKeyProvider`] — never for regulated production.
//!
//! ## Honest zero-knowledge path
//!
//! Encrypt/decrypt touch plaintext in process memory. This crate does not
//! claim cryptographic zero-knowledge for those steps.

#![forbid(unsafe_code)]

use std::collections::{HashMap, HashSet};
use std::io::Cursor;

use crypt4gh::keys::{generate_private_key, get_public_key_from_private_key};
use crypt4gh::{decrypt, encrypt, Keys};
use serde::{Deserialize, Serialize};
use thiserror::Error;

